"""Generate the unshared arithmetic control from C's unchanged FP shell."""
import hashlib
import json
import random
from pathlib import Path

HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[1]
SOURCES=[ROOT/'rtl/root_opt/oadm_fixed_divmul_root_opt.v',
         ROOT/'experiments/fixed_div_level_specialization/specialized_rtl.v',
         ROOT/'rtl/mul_root_opt/oadm_mul_root_opt.v',
         ROOT/'PACE/common/FP_DIV_WRAPPER_32.v']

def main():
    source=SOURCES[0].read_text()
    start=source.index('    wire [2:0] x_index')
    end=source.index('    reg [COEFFICIENT_BITS-1:0] coefficient;')
    independent='''    wire signed [28:0] plane_value;
    wire signed [28:0] mul_plane_value;
    oadm_fixed_div_specialized_plane #(
        .LEVEL(LEVEL), .RESIDUAL_DROP(DIV_RESIDUAL_DROP)
    ) div_plane (
        .x_mantissa(x_mantissa), .y_mantissa(y_mantissa),
        .plane_exact(plane_value)
    );
    oadm_fixed_mul_plane_root_opt #(
        .LEVEL(LEVEL), .RESIDUAL_DROP(MUL_RESIDUAL_DROP)
    ) mul_plane (
        .x_mantissa(x_mantissa), .y_mantissa(y_mantissa),
        .plane_value(mul_plane_value)
    );

'''
    derived=source[:start]+independent+source[end:]
    old='? divided_value : plane_value;'
    assert derived.count(old)==1
    derived=derived.replace(old,'? divided_value : mul_plane_value;')
    derived=derived.replace('oadm_fixed_divmul_root_opt','oadm_fixed_divmul_unshared')
    for l in range(4):
        derived=derived.replace(f'oadm_fixed_l{l}_divmul_root_opt',f'oadm_fixed_l{l}_divmul_unshared')
    (HERE/'unshared.v').write_text('// Generated by prepare.py; original C is unchanged.\n'+derived)
    (HERE/'source_sha256.json').write_text(json.dumps({str(p.relative_to(ROOT)):
        hashlib.sha256(p.read_bytes()).hexdigest() for p in SOURCES},indent=2)+'\n')
    import difflib
    (HERE/'shell_changes.diff').write_text(''.join(difflib.unified_diff(source.splitlines(True),derived.splitlines(True),
        fromfile='original_shared_C',tofile='independent_arithmetic_B')))
    rng=random.Random(20260905); mask=(1<<23)-1
    vectors=[(0,0x3f800000|rng.getrandbits(23),0x3f800000|rng.getrandbits(23)) for _ in range(100000)]
    edges={v for k in range(17) for d in (-1,0,1) if 0<=(v:=k*(1<<19)+d)<=mask}
    vectors += [(1,0x3f800000|x,0x3f800000|y) for x in sorted(edges) for y in sorted(edges)]
    for _ in range(2000):
        x=(rng.getrandbits(1)<<31)|(rng.randrange(110,145)<<23)|rng.getrandbits(23)
        y=(rng.getrandbits(1)<<31)|(rng.randrange(110,145)<<23)|rng.getrandbits(23)
        vectors.append((2,x,y))
    (HERE/'inputs.txt').write_text(''.join(f'{ds} {x:08x} {y:08x}\n' for ds,x,y in vectors))
    counts={str(i):sum(ds==i for ds,_,_ in vectors) for i in range(3)}
    (HERE/'counts.json').write_text(json.dumps(counts,indent=2)+'\n')
    for l in range(4):
        tb=f'''`timescale 1ns/1ps
module tb;
reg [31:0] x,y; reg divide_mode;
wire [31:0] b,c,d,m;
oadm_fixed_l{l}_divmul_unshared B(x,y,divide_mode,b);
oadm_fixed_l{l}_divmul_root_opt C(x,y,divide_mode,c);
oadm_fixed_l{l}_div_specialized D(x,y,d);
oadm_fixed_l{l}_mul_root_opt M(x,y,m);
`ifdef GATE
wire [31:0] bg,cg;
oadm_fixed_l{l}_divmul_unshared_gate BG(x,y,divide_mode,bg);
oadm_fixed_l{l}_divmul_root_opt_gate CG(x,y,divide_mode,cg);
`endif
integer fd,fo,status,ds,n=0,checked=0,mode;
initial begin
fd=$fopen("{HERE}/inputs.txt","r");
if(!fd) $fatal(1,"input file missing");
`ifndef GATE
fo=$fopen("{HERE}/outputs_l{l}.txt","w");
`endif
while(!$feof(fd)) begin
 status=$fscanf(fd,"%d %h %h\\n",ds,x,y);
 if(status==3) begin
`ifdef GATE
 if(ds!=0 || n<1000) begin
`endif
 for(mode=0;mode<2;mode=mode+1) begin
 divide_mode=mode; #10; checked=checked+1;
 if(b !== c || b !== (divide_mode ? d : m))
   $fatal(1,"RTL MISMATCH L{l} mode=%0d x=%h y=%h b=%h c=%h d=%h m=%h",mode,x,y,b,c,d,m);
`ifdef GATE
 if(b !== bg || c !== cg) $fatal(1,"GATE MISMATCH L{l} mode=%0d x=%h y=%h",mode,x,y);
`else
 $fwrite(fo,"%d %d %h %h %h\\n",ds,mode,x,y,b);
`endif
 end
`ifdef GATE
 end
`endif
 n=n+1;
 end
end
`ifdef GATE
if(checked!={2*(1000+counts['1']+counts['2'])}) $fatal(1,"gate count");
`else
if(checked!={2*len(vectors)}) $fatal(1,"RTL count");
$fclose(fo);
`endif
$fclose(fd);
$display("ARITHMETIC_SHARING PASS L{l} checked=%0d",checked);
$finish;
end
endmodule
'''
        (HERE/f'tb{l}.sv').write_text(tb)
    print(f'Generated B and {len(vectors)} pairs, both modes per pair')

if __name__=='__main__':main()
